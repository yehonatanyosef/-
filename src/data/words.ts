import type { Word } from '../types';

type Row = [en: string, he: string, emoji: string, level: number, swatch?: string];

function topic(name: string, rows: Row[]): Word[] {
  return rows.map(([en, he, emoji, level, swatch]) => ({
    id: `${name}-${en.replace(/\s+/g, '_')}`,
    en,
    he,
    emoji,
    level,
    topic: name,
    ...(swatch ? { swatch } : {}),
  }));
}

